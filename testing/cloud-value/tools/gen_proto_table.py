#!/usr/bin/env python3
"""Generates crates/hguet-cloud/src/proto_table.rs from the public protocol/v1/hguet.proto (via proto_codec.SCHEMA).

    python3 testing/cloud-value/tools/gen_proto_table.py          # rewrite the file
    python3 testing/cloud-value/tools/gen_proto_table.py --check  # exit 1 if the file drifted from the proto
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
sys.dont_write_bytecode = True
sys.path.insert(0, str(ROOT / "testing/cloud-value/protocol"))
import proto_codec  # noqa: E402

TARGET = ROOT / "crates/hguet-cloud/src/proto_table.rs"


def render():
    enums, messages = proto_codec.SCHEMA["enums"], proto_codec.SCHEMA["messages"]

    def kind(typ):
        simple = {"string": "Kind::String", "bytes": "Kind::Bytes", "bool": "Kind::Bool", "uint32": "Kind::U32",
                  "uint64": "Kind::U64"}
        if typ in simple:
            return simple[typ]
        return 'Kind::Enum("%s")' % typ if typ in enums else 'Kind::Message("%s")' % typ

    lines = ["//! GENERATED by testing/cloud-value/tools/gen_proto_table.py from protocol/v1/hguet.proto.",
             "//! Do not edit; `gen_proto_table.py --check` fails (and CI with it) if this drifts from the schema.",
             "use crate::proto_policy::{Field, Kind};", "", "pub const ENUMS: &[(&str, &[i64])] = &["]
    for name, values in sorted(enums.items()):
        lines.append('    ("%s", &[%s]),' % (name, ", ".join(str(v) for v in sorted(values.values()))))
    lines += ["];", "", "pub const MESSAGES: &[(&str, &[Field])] = &["]
    for name in sorted(messages):
        lines.append('    ("%s", &[' % name)
        for number, f in sorted(messages[name]["fields"].items()):
            lines.append('        Field { number: %d, kind: %s, repeated: %s, oneof: %s },' % (
                number, kind(f["type"]), "true" if f["repeated"] else "false",
                'Some("%s")' % f["oneof"] if f["oneof"] else "None"))
        lines.append("    ]),")
    lines.append("];")
    return "\n".join(lines) + "\n"


def main():
    text = render()
    if "--check" in sys.argv:
        current = TARGET.read_bytes().decode("utf-8").replace("\r\n", "\n") if TARGET.exists() else ""
        if current != text:
            print("DRIFT: %s does not match protocol/v1/hguet.proto" % TARGET)
            return 1
        print("OK: proto_table.rs matches the public schema")
        return 0
    TARGET.write_bytes(text.encode("utf-8"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
